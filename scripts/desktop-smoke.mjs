import { _electron as electron } from 'playwright-core';
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';

const profile=await mkdtemp(path.join(os.tmpdir(),'blink-smoke-'));
const executablePath=path.resolve(process.argv[2]);
const launch=()=>electron.launch({executablePath,args:['--user-data-dir='+profile],timeout:60000});
let instance;
try {
  instance=await launch();
  await instance.context().setOffline(true);
  let page=await instance.firstWindow();
  await page.reload({waitUntil:'domcontentloaded',timeout:60000});
  await page.locator('#countdown').waitFor();
  assert.equal(await page.locator('html').getAttribute('data-platform'),'desktop');
  const nav=await page.locator('#nav').boundingBox();
  const timer=await page.locator('.timer-panel').boundingBox();
  assert.ok(nav.x+nav.width<timer.x);
  await page.evaluate(()=>say('测试消息'));
  const toast=await page.getByRole('status').filter({hasText:'测试消息'}).boundingBox();
  const viewport=await page.evaluate(()=>({width:innerWidth,height:innerHeight}));
  assert.equal(Math.round(viewport.width-toast.x-toast.width),22);
  assert.equal(Math.round(viewport.height-toast.y-toast.height),22);
  await page.locator('#offMode').click();
  assert.equal(await page.locator('#offMode').getAttribute('aria-pressed'),'true');
  await page.locator('#workMode').click();
  assert.equal(await page.locator('#workMode').getAttribute('aria-pressed'),'true');
  await page.getByRole('button',{name:'日程',exact:true}).click();
  await page.locator('#planMode').getByRole('button',{name:'工作日',exact:true}).click();
  await page.getByLabel('晚餐开始').fill('17:45');
  await page.getByLabel('晚餐开始').press('Tab');
  await page.locator('#appearance').selectOption('dark');
  assert.equal(await page.locator('html').getAttribute('data-theme'),'dark');
  await page.locator('#delivery summary').click();
  await page.getByRole('checkbox',{name:'系统通知'}).check();
  await page.getByRole('button',{name:'今日',exact:true}).click();
  await page.locator('#workMode[aria-pressed="true"]').waitFor();
  const main=await instance.browserWindow(page);
  await main.evaluate(win=>win.minimize());
  await page.waitForFunction(()=>pageHidden());
  assert.equal(await main.evaluate(win=>win.isMinimized()),true);
  const popupPromise=instance.waitForEvent('window',{timeout:10000});
  await page.evaluate(()=>{
    data.lunchEnd=data.lunchStart;
    data.dinnerEnd=data.dinnerStart;
    settle();
    data.progress[2]=frequency(2)*minute-500;
    scheduleTick();
  });
  const reminder=await popupPromise;
  const reminderWindow=await instance.browserWindow(reminder);
  const bounds=await reminderWindow.evaluate(win=>win.getBounds());
  const area=await instance.evaluate(({screen},rect)=>screen.getDisplayMatching(rect).workArea,bounds);
  assert.equal(area.x+area.width-bounds.x-bounds.width,16);
  assert.equal(area.y+area.height-bounds.y-bounds.height,16);
  const closed=reminder.waitForEvent('close',{timeout:10000});
  await reminder.getByRole('button',{name:'喝过了',exact:true}).click();
  await closed;
  await main.evaluate(win=>win.restore());
  await page.waitForFunction(()=>!pageHidden());
  await page.getByRole('button',{name:'记录',exact:true}).click();
  await page.locator('#feed .recorded').first().waitFor();
  assert.equal(await page.locator('#feed .recorded').count(),1);
  await page.getByRole('button',{name:'记一次',exact:true}).click();
  await page.getByRole('dialog').getByRole('button',{name:'喝水',exact:true}).click();
  assert.equal(await page.locator('#feed .recorded').count(),2);
  const exit=instance.waitForEvent('close',{timeout:10000});
  await main.evaluate(win=>{win.close()}).catch(error=>{
    if(!/closed/i.test(error.message))throw error;
  });
  await exit;
  instance=await launch();
  await instance.context().setOffline(true);
  page=await instance.firstWindow();
  await page.getByRole('button',{name:'记录',exact:true}).click();
  await page.locator('#feed .recorded').first().waitFor();
  assert.equal(await page.locator('html').getAttribute('data-theme'),'dark');
  assert.equal(await page.locator('#feed .recorded').count(),2);
  assert.match(await page.locator('#feed .recorded').first().innerText(),/喝水/);
  await page.getByRole('button',{name:'日程',exact:true}).click();
  await page.locator('#planMode').getByRole('button',{name:'工作日',exact:true}).click();
  assert.equal(await page.getByLabel('晚餐开始').inputValue(),'17:45');
  console.log('Minimized app delivered a reminder, closing quit the app, and check-ins survived restart.');
} finally {
  if(instance)await instance.close().catch(()=>{});
  await rm(profile,{recursive:true,force:true,maxRetries:4,retryDelay:300});
}
